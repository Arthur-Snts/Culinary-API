def update_avaliacao(session:SessionDep, avaliacao:Avaliacao):
    avaliacao_antigo = session.exec(select(Avaliacao).where(Avaliacao.receita_id ==avaliacao.receita_id and Avaliacao.usuario_id == avaliacao.usuario_id)).one_or_none()
