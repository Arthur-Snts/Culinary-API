#////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
                                                        #USUARIOS PUT
#////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

def update_usuario(session:SessionDep, usuario:Usuario):
    usuario_antigo = session.exec(select(Usuario).where(Usuario.id == usuario.id)).one_or_none()
    if usuario_antigo !=None:
        usuario_antigo.nome = usuario.nome
        usuario_antigo.email = usuario.email
        usuario_antigo.senha = usuario.senha
        session.add(usuario_antigo)
        session.commit()
    

#////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
                                                        #RECEITAS PUT
#////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

def update_receita(session:SessionDep, receita:Receita):
    receita_antigo = session.exec(select(Receita).where(Receita.id == receita.id)).one_or_none()
    if receita_antigo != None:
        receita_antigo.nome = receita.nome
        receita_antigo.descricao = receita.descricao
        receita_antigo.ingredientes = receita.ingredientes
        receita_antigo.modo_preparo = receita.modo_preparo
        receita_antigo.usuario_id = receita.usuario_id
        session.add(receita_antigo)
        session.commit()
    

#////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
