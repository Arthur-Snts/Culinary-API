from sqlmodel import select, Session
from models import Avaliacao, Receita, Usuario, Comentario, Favorito
from config import engine
from fastapi import Depends
from typing import Annotated

def get_session():
    with Session(engine) as session:
        yield session

SessionDep = Annotated[Session, Depends(get_session)]

#////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
                                                        #USUARIOS GET
#////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

def usuarios_all(session:SessionDep):
    usuarios = session.exec(select(Usuario)).all()
    return usuarios

#////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
                                                        #RECEITAS GET
#////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

def receitas_all(session:SessionDep):
    receitas = session.exec(select(Receita)).all()
    return receitas

def receita_one(session:SessionDep, nome:str):
    receita = session.exec(select(Receita).where(Receita.nome == nome)).one_or_none()
    return receita

#////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
                                                        #FAVORITOS GET
